// ---------------------------------------------------------------------------
// Release signing
//
// The release keystore is NEVER committed. CI writes `keystore.properties`
// (or exports the ANDROID_KEYSTORE_* env vars) from repository secrets;
// locally you can point the same properties at your own keystore:
//
//   mobile/keystore.properties:
//     storeFile=release.keystore
//     storePassword=…
//     keyAlias=…
//     keyPassword=…
//
// Without any of it, `assembleRelease` still builds — it just falls back to
// the debug key, which is installable but not suitable for publishing.
// ---------------------------------------------------------------------------
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.isFile) file.inputStream().use { load(it) }
}

fun signingValue(property: String, env: String): String? =
    keystoreProperties.getProperty(property)?.takeIf { it.isNotBlank() }
        ?: System.getenv(env)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("storeFile", "ANDROID_KEYSTORE_FILE")
val releaseStorePassword = signingValue("storePassword", "ANDROID_KEYSTORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "ANDROID_KEY_ALIAS")
val releaseKeyPassword = signingValue("keyPassword", "ANDROID_KEY_PASSWORD")

val hasReleaseSigning = listOf(
    releaseStoreFile,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword
).all { it != null }

android {
    namespace = "com.jasonbible.phone"
    compileSdk = 35

